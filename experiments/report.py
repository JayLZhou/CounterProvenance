#!/usr/bin/env python3
"""Assemble results/*.csv into results/RESULTS.md."""

from __future__ import annotations

import csv
import math
from collections import defaultdict

from common import RESULTS, environment, markdown_table


def load(name: str) -> list[dict]:
    """Rows of ``name`` plus every parallel-run file ``<stem>_<suffix>.csv``."""
    stem = name[:-4]
    paths = sorted(RESULTS.glob(f"{stem}.csv")) + sorted(RESULTS.glob(f"{stem}_*.csv"))
    rows: list[dict] = []
    seen = set()
    for path in paths:
        with path.open(encoding="utf-8") as handle:
            for row in csv.DictReader(handle):
                key = tuple(sorted(row.items()))
                if key not in seen:
                    seen.add(key)
                    rows.append(row)
    for row in rows:
        for key, value in list(row.items()):
            if value is None:
                row[key] = "-"
                continue
            if value in ("", None):
                row[key] = "-"
                continue
            try:
                number = float(value)
                row[key] = int(number) if number.is_integer() and "." not in value and "e" not in value.lower() else number
            except ValueError:
                pass
    return rows


def ratio(a, b) -> float:
    try:
        return float(a) / float(b)
    except (TypeError, ValueError, ZeroDivisionError):
        return float("nan")


def main() -> None:
    out: list[str] = ["# Results", ""]
    env = environment()
    out.append("Generated by `experiments/report.py` from the CSV files in this directory. "
               "Records are structural words (PFT nodes, modification entries, face roots and values, "
               "locator cells, item references, segment-tree nodes); bytes are estimated packed sizes. "
               "Query times are single-threaded pure Python and comparable only to each other.")
    out.append("")
    out.append("Environment: " + ", ".join(f"{k} {v}" for k, v in env.items() if k != "platform"))
    out.append("")

    e1 = load("e1_1d_chain.csv")
    if e1:
        out += ["## E1. 1D sparse-change family (B = M = n)", ""]
        for r in e1:
            r["vs_iip"] = ratio(r.get("iip_records"), r.get("records"))
        out.append(markdown_table(e1, [("n", "n"), ("index", "layout"), ("faces", "regions"), ("pft_nodes", "PFT nodes"),
                                       ("pft_entries", "entries"), ("records", "records"), ("iip_records", "IIP records"),
                                       ("vs_iip", "IIP / ours")]))
        out.append("")

    e2 = load("e2_2d_grid.csv")
    if e2:
        out += ["## E2. 2D general-position stump grids", ""]
        for r in e2:
            r["vs_iip"] = ratio(r.get("iip_records"), r.get("records"))
        out.append(markdown_table(e2, [("workload", "workload"), ("index", "index"), ("faces", "faces"),
                                       ("records", "records"), ("bytes", "bytes"), ("iip_records", "IIP records"),
                                       ("vs_iip", "IIP / ours"), ("mean_pieces", "pieces"), ("build_s", "build s")]))
        out.append("")

    e3 = load("e3_coincidence.csv")
    if e3:
        out += ["## E3. Coincident thresholds (kappa trees change per boundary, M = 256)", ""]
        out.append(markdown_table(e3, [("kappa", "kappa"), ("index", "index"), ("faces", "faces"),
                                       ("walk_cost", "plan cost"), ("pft_nodes", "PFT nodes"), ("pft_entries", "entries"),
                                       ("records", "records"), ("iip_records", "IIP records")]))
        out.append("")

    e4 = load("e4_mst_ablation.csv")
    if e4:
        out += ["## E4. Heterogeneous edge costs: does the MST matter?", ""]
        out.append(markdown_table(e4, [("index", "plan"), ("faces", "faces"), ("tree_weight", "plan weight"),
                                       ("pft_nodes", "PFT nodes"), ("pft_entries", "entries"), ("records", "records")]))
        out.append("")

    r1 = load("r1_compilers.csv")
    if r1:
        out += ["## R1. Compiler exactness on California housing", ""]
        out.append(markdown_table(r1, [("model", "model"), ("trees", "trees"), ("max_value_error", "max |ours - model.predict|"),
                                       ("leaf_id_match", "leaf ids equal to model API")]))
        out.append("")
        out.append("XGBoost accumulates leaf values in float32, hence its 1e-6 differences; every other model agrees "
                   "to floating-point summation order. Leaf ids are compared with `apply`, `pred_leaf=True`, or "
                   "LightGBM's `pred_leaf=True`, including rows placed exactly on split thresholds.")
        out.append("")

    r2 = load("r2_real_indexes.csv")
    if r2:
        out += ["## R2. Index size, pieces and latency on real models", ""]
        out.append("Every listed index was checked on random and threshold what-if points: values against "
                   "`model.predict`, provenance against brute force and the model's own leaf ids.")
        out.append("")
        by = defaultdict(dict)
        meta = {}
        for r in r2:
            key = (r["model"], r["d"])
            meta[key] = r
            label = str(r["index"])
            kind = ("one" if label.startswith("one MCPST") else "grouped" if label.startswith("grouped")
                    else "chain" if label.startswith("chain") else "auto")
            by[key][kind] = r
        rows = []
        for key, kinds in by.items():
            m = meta[key]
            row = {"model": key[0], "d": key[1], "N": m.get("N_boxes"), "K_grid": m.get("K_grid"),
                   "replay_us": m.get("replay_us")}
            one = kinds.get("one")
            if one and one.get("records", "-") != "-":
                row["iip"] = one.get("iip_records")
                row["one"] = one.get("records")
                row["one_q"] = one.get("query_us")
            else:
                row["iip"] = row["one"] = row["one_q"] = "infeasible"
            chain = kinds.get("chain", {})
            row["chain"] = chain.get("records")
            row["chain_p"] = chain.get("mean_pieces")
            auto = kinds.get("auto", {})
            row["auto"] = auto.get("records")
            row["auto_p"] = auto.get("mean_pieces")
            row["auto_q"] = auto.get("query_us")
            row["auto_cfg"] = str(auto.get("index", "-")).replace("autotuned (pieces<=16): ", "")
            rows.append(row)
        out.append(markdown_table(rows, [
            ("model", "model"), ("d", "d"), ("N", "boxes N"), ("K_grid", "grid cells"),
            ("iip", "IIP records"), ("one", "one MCPST records"), ("one_q", "one MCPST us"),
            ("chain", "tau=0 records"), ("chain_p", "tau=0 pieces"),
            ("auto", "autotuned records"), ("auto_p", "autotuned pieces"), ("auto_q", "autotuned us"),
            ("auto_cfg", "chosen (tau, groups)"), ("replay_us", "model.predict us"),
        ]))
        out.append("")

    r3 = load("r3_mst_real.csv")
    if r3:
        out += ["## R3. Boundary statistics and the MST on real d = 2 overlays", ""]
        out.append(markdown_table(r3, [("model", "model"), ("layout", "layout"), ("spanning", "spanning tree"),
                                       ("faces", "faces"), ("grid_cells", "grid cells"), ("mean_c", "mean c_e"),
                                       ("max_c", "max c_e"), ("frac_c_gt_1", "share c_e > 1"),
                                       ("pft_records", "PFT records"), ("records", "records")]))
        out.append("")

    r4 = load("r4_dowhy.csv")
    if r4:
        out += ["## R4. End to end against DoWhy-GCM", ""]
        out.append("Each query is a separate `counterfactual_samples` call (fresh: with `observed_data`, i.e. "
                   "abduction + action + prediction; cached: with `noise_data`). Fitting is excluded. "
                   "Answers are compared query by query.")
        out.append("")
        out.append(markdown_table(r4, [("model", "model"), ("d", "d"), ("intervened", "do() on"), ("index", "index"),
                                       ("dowhy_fresh_us", "DoWhy fresh us"), ("dowhy_cached_noise_us", "DoWhy cached us"),
                                       ("index_us", "index us"), ("speedup_vs_fresh", "x vs fresh"),
                                       ("speedup_vs_cached", "x vs cached"), ("mean_pieces", "pieces"),
                                       ("max_abs_error", "max |error|")]))
        out.append("")

    r5 = load("r5_highdim.csv")
    if r5:
        r5.sort(key=lambda r: (str(r["dataset"]), str(r["model"]), int(r["d"])))
        out += ["## R5. Hundreds of features: d = 2, 8, 16 interventions", ""]
        out.append("Star SCM `every feature -> Y` fitted with DoWhy-GCM on OpenML datasets with hundreds of "
                   "continuous features; the intervened features are the ones the ensemble splits on most. "
                   "`effective trees` counts trees that still split on an intervened feature after binding the "
                   "unit; all other trees collapse to one constant piece. Index chosen by `autotune` "
                   "(pieces <= 16). Single-threaded throughout.")
        out.append("")
        out.append(markdown_table(r5, [("dataset", "dataset"), ("features", "features"), ("model", "model"),
                                       ("d", "d"), ("effective_trees", "effective trees"), ("trees", "trees"),
                                       ("N_boxes", "boxes N"), ("index_records", "index records"),
                                       ("mean_pieces", "pieces"), ("index_us", "index us"),
                                       ("predict_us", "predict us"), ("dowhy_fresh_us", "DoWhy fresh us"),
                                       ("dowhy_cached_us", "DoWhy cached us"), ("x_vs_dowhy_fresh", "x vs fresh"),
                                       ("x_vs_dowhy_cached", "x vs cached"), ("x_vs_predict", "x vs predict"),
                                       ("build_s", "build s"), ("max_abs_error", "max |error|")]))
        out.append("")

    (RESULTS / "RESULTS.md").write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {RESULTS / 'RESULTS.md'}")


if __name__ == "__main__":
    main()
