    b.append(r"\legend{" + ",".join(nm for _, _, nm in M5) + "}")
    for i in range(1, n + 1, 2):  # a light band behind every other group
        b.append(r"\fill[cband] (axis cs:%g,2) rectangle (axis cs:%g,1e6);" % (i - 0.5, i + 0.5))
    for i, g in enumerate(groups, 1):
        for j, (k, col, _) in enumerate(M5):
            x, vals = i + (j - 2) * sep, g[k]
            m = len(vals)
            pts = " ".join("(%.3f,%.5g)" % (x + (t - (m - 1) / 2) * jit * 5 / max(m, 5), v) for t, v in enumerate(vals))
            b.append(r"\addplot[only marks, forget plot, mark=%s, mark size=1.5pt, mark options={%s}] coordinates {%s};" % (marks[k], "mkours" if k == "twin" else "mk=" + col, pts))
            mean = sum(vals) / m
