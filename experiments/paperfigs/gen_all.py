import re
def _sentence(text):
    return re.sub(r"((?:x|y)label|title)=\{([a-z])", lambda m: m.group(1) + "={" + m.group(2).upper(), text).replace("ylabel={\\# leaf records}", "ylabel={Leaf records}")


def write(name, lines, comment):
    with open(os.path.join(OUT, name + ".tex"), "w") as f:
        f.write("% " + comment + " Generated by CounterProvenance/experiments/paperfigs/gen_all.py; style in figures/expstyle.tex.\n")
        f.write(_sentence("\n".join(lines)).replace("$\\times$", "×").replace("\\,$\\mu$s", "\\,µs").replace("mk=ctwin", "mkours").replace("fill=ctwin!45", "fill=ctwin!72") + "\n")


def human_s(s):
    if s < 1: return f"{s * 1000:.0f}\\,ms"
    if s < 10: return f"{s:.1f}\\,s"
    if s < 60: return f"{s:.0f}\\,s"
    if s < 600: return f"{s / 60:.1f}\\,min"
    if s < 3600: return f"{s / 60:.0f}\\,min"
    if s < 86400: return f"{s / 3600:.1f}\\,h"
    return f"{s / 86400:.1f}\\,d"


def coords(xs, ys):
    return " ".join(f"({x},{y:.6g})" for x, y in zip(xs, ys) if y is not None)


def figure(env, body, caption, label):
    return [r"\begin{%s}[t]" % env, r"\centering", r"\begin{tikzpicture}"] + body + [r"\end{tikzpicture}", r"\caption{%s}" % caption, r"\label{%s}" % label, r"\end{%s}" % env]


