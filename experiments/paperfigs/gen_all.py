def dots(rows, labels, width, height, legend_at):
    n = len(rows)
    ticks = ["{%s\\\\\\textcolor{ctwin}{\\bfseries %.0f$\\times$}}" % (l, r["three_step"] / r["twin"]) for l, r in zip(labels, rows)]
